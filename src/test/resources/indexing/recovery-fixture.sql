-- 전용 폐기 가능한 PostgreSQL 클러스터에서만 사용한다. 원문/벡터 없이 실제 큐 제약을 재현한다.
CREATE TABLE public.document (
    id BIGINT PRIMARY KEY,
    deleted_at TIMESTAMPTZ,
    execution_epoch BIGINT NOT NULL DEFAULT 0 CHECK (execution_epoch >= 0)
);
CREATE TABLE public.document_version (
    id BIGINT PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES public.document(id),
    UNIQUE (id, document_id)
);
CREATE TABLE public.indexing_job (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_event_id UUID NOT NULL UNIQUE,
    document_id BIGINT NOT NULL REFERENCES public.document(id),
    document_version_id BIGINT,
    job_type VARCHAR(20) NOT NULL,
    enqueue_seq BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    status VARCHAR(30) NOT NULL CHECK (status IN ('PENDING','PROCESSING','RETRY_WAIT','COMPLETED','FAILED')),
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    execution_epoch BIGINT NOT NULL DEFAULT 0 CHECK (execution_epoch >= 0),
    lease_until TIMESTAMPTZ,
    worker_id VARCHAR(255),
    next_retry_at TIMESTAMPTZ,
    phase VARCHAR(30),
    outcome VARCHAR(40),
    last_error_code VARCHAR(100),
    last_error_message TEXT,
    trace_id VARCHAR(255),
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (document_version_id, document_id) REFERENCES public.document_version(id, document_id),
    CHECK ((job_type = 'INDEX' AND document_version_id IS NOT NULL)
        OR (job_type = 'DELETE' AND document_version_id IS NULL)),
    CHECK ((status = 'PROCESSING' AND worker_id IS NOT NULL AND lease_until IS NOT NULL)
        OR (status IN ('PENDING','RETRY_WAIT','COMPLETED','FAILED') AND worker_id IS NULL AND lease_until IS NULL))
);
CREATE UNIQUE INDEX uq_indexing_job_active_version ON public.indexing_job (document_version_id)
    WHERE status IN ('PENDING','PROCESSING','RETRY_WAIT');
CREATE INDEX idx_indexing_job_expired_lease ON public.indexing_job (lease_until) WHERE status = 'PROCESSING';
