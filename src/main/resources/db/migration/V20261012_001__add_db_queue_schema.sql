-- =============================================================================
-- DB Job 큐 스키마
--
-- Kafka 기반 작업 전달을 DB Job 큐로 대체한다. 실행 번호(execution_epoch),
-- lease, 등록 순서(enqueue_seq), 외부 API 서킷 브레이커 테이블을 추가한다.
--
-- 스키마는 API 서버가 소유하고 Flyway 로 적용한다. Worker 는 적용하지 않는다.
--
-- 적용 전 Kafka 로 Job 을 받는 기존 Worker 를 멈추고 PROCESSING Job 을 비운다.
-- PROCESSING Job 이 남아 있으면 아래 검사에서 중단한다.
--
-- Job 회수 절차, external_circuit_result 정리, 스케줄러는 이 파일에 넣지 않는다.
-- =============================================================================

-- PROCESSING Job 잔존 검사
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM indexing_job WHERE status = 'PROCESSING') THEN
        RAISE EXCEPTION 'Stop/drain or externally recover PROCESSING Jobs before this migration';
    END IF;
END $$;


-- -----------------------------------------------------------------------------
-- document
-- -----------------------------------------------------------------------------

ALTER TABLE document
    ADD COLUMN execution_epoch BIGINT NOT NULL DEFAULT 0;

ALTER TABLE document
    ADD CONSTRAINT ck_document_execution_epoch
        CHECK (execution_epoch >= 0);

COMMENT ON COLUMN document.execution_epoch IS
    '문서 단위 실행 번호. 해당 문서의 Job 을 claim 할 때마다 증가하며 초기화하지 않는다. 이전 Worker 의 늦은 변경을 막는 데 쓴다.';


-- -----------------------------------------------------------------------------
-- indexing_job
--
-- DELETE Job 은 문서 단위라 document_version_id 가 없으므로 NULL 을 허용한다.
-- Kafka record 위치 컬럼은 DB 큐로 바뀌며 쓰지 않아 지운다.
-- -----------------------------------------------------------------------------

ALTER TABLE indexing_job
    ADD COLUMN job_type VARCHAR(20) NOT NULL DEFAULT 'INDEX',
    ADD COLUMN enqueue_seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ADD COLUMN execution_epoch BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN lease_until TIMESTAMPTZ,
    ADD COLUMN outcome VARCHAR(40),
    ALTER COLUMN document_version_id DROP NOT NULL,
    DROP COLUMN kafka_topic,
    DROP COLUMN kafka_partition,
    DROP COLUMN kafka_offset;

-- 기존 행 enqueue_seq 재부여
-- IDENTITY 컬럼 추가 시 채워지는 값은 물리 저장 순서라, 등록 순서(created_at, id)로 다시 매긴다.
-- 시퀀스는 그 최댓값 다음부터 이어지게 맞추고, 행이 없으면 1 부터 시작하게 둔다.
WITH ordered AS (
    SELECT id, row_number() OVER (ORDER BY created_at, id) AS seq
    FROM indexing_job
)
UPDATE indexing_job j
SET enqueue_seq = o.seq
FROM ordered o
WHERE j.id = o.id;

SELECT setval(
    pg_get_serial_sequence('indexing_job', 'enqueue_seq'),
    COALESCE((SELECT MAX(enqueue_seq) FROM indexing_job), 1),
    EXISTS (SELECT 1 FROM indexing_job)
);

-- Kafka 기반 Worker 가 종결 Job 에 남긴 worker_id 를 비운다.
-- 아래 ck_indexing_job_lease 가 PROCESSING 이 아닌 Job 의 worker_id 를 허용하지 않는다.
UPDATE indexing_job
SET worker_id = NULL
WHERE worker_id IS NOT NULL;

-- DELETE Job 은 document_version_id 가 NULL 이라 기존 복합 FK
-- (fk_indexing_job_document_version)가 검사되지 않는다. document 에 직접 FK 를 건다.
ALTER TABLE indexing_job
    ADD CONSTRAINT fk_indexing_job_document
        FOREIGN KEY (document_id)
        REFERENCES document(id),
    ADD CONSTRAINT ck_indexing_job_type
        CHECK (
            (job_type = 'INDEX' AND document_version_id IS NOT NULL)
            OR (job_type = 'DELETE' AND document_version_id IS NULL)
        ),
    ADD CONSTRAINT ck_indexing_job_epoch
        CHECK (execution_epoch >= 0),
    ADD CONSTRAINT ck_indexing_job_lease
        CHECK (
            (status = 'PROCESSING' AND worker_id IS NOT NULL AND lease_until IS NOT NULL)
            OR (status IN ('PENDING', 'RETRY_WAIT', 'COMPLETED', 'FAILED')
                AND worker_id IS NULL AND lease_until IS NULL)
        );

CREATE UNIQUE INDEX uq_indexing_job_enqueue_seq
    ON indexing_job (enqueue_seq);

COMMENT ON COLUMN indexing_job.job_type IS
    'INDEX: 임베딩 / DELETE: 기존 청크·벡터 정리. 삭제된 문서에서도 DELETE 작업 자체는 수행한다.';
COMMENT ON COLUMN indexing_job.enqueue_seq IS
    '전역 증가형 등록 순서. 실행 가능한 Job 을 오래된 순으로 고르고, 같은 문서의 선행 Job 을 비교하는 데 쓴다. 값 사이에 빈 번호가 생길 수 있다.';
COMMENT ON COLUMN indexing_job.execution_epoch IS
    'claim 시 document.execution_epoch 에서 받은 실행 번호. claim 전에는 0 이다.';
COMMENT ON COLUMN indexing_job.lease_until IS
    '현재 실행권 만료 시각. heartbeat 로 연장하며, 실행권이 없으면 NULL 이다.';
COMMENT ON COLUMN indexing_job.outcome IS
    '완료 사유. 예: INDEXED, DELETED, SKIPPED_DOCUMENT_DELETED. 값이 늘 수 있어 CHECK 제약은 두지 않는다.';

-- document_version.embedding_version_no 와 document.latest_embedding_version_no 는
-- Core 가 소유한 공용 메타데이터라 지우지 않는다. Worker 가 앞의 컬럼을 더 이상
-- 매핑하지 않아도 컬럼 삭제 근거가 되지 않는다.


-- -----------------------------------------------------------------------------
-- indexing_job 미종결 Job 조회용 partial index
--
-- 완료·실패 이력 전체를 매번 순회하지 않도록 미종결 상태만 인덱싱한다.
-- -----------------------------------------------------------------------------

-- 같은 문서의 앞선 미종결 Job 확인
CREATE INDEX idx_indexing_job_document_order
    ON indexing_job (document_id, enqueue_seq)
    WHERE status IN ('PENDING', 'PROCESSING', 'RETRY_WAIT');

-- claim 후보를 등록 순서대로 조회
CREATE INDEX idx_indexing_job_claim_order
    ON indexing_job (enqueue_seq)
    WHERE status IN ('PENDING', 'RETRY_WAIT');

-- 재시도 시각이 된 Job 조회
CREATE INDEX idx_indexing_job_retry_due
    ON indexing_job (next_retry_at)
    WHERE status = 'RETRY_WAIT';

-- lease 가 만료된 Job 회수
CREATE INDEX idx_indexing_job_expired_lease
    ON indexing_job (lease_until)
    WHERE status = 'PROCESSING';


-- -----------------------------------------------------------------------------
-- external_circuit_breaker
--
-- 외부 API 별 서킷 브레이커 상태. HALF_OPEN 일 때만 probe 를 맡은 소유자가 있고,
-- probe 호출 중일 때만 probe_call_id 와 probe_call_until 이 함께 채워진다.
-- -----------------------------------------------------------------------------

CREATE TABLE external_circuit_breaker (
    name                    VARCHAR(50) PRIMARY KEY,
    state                   VARCHAR(20) NOT NULL DEFAULT 'CLOSED',
    consecutive_failures    INT NOT NULL DEFAULT 0,
    opened_until            TIMESTAMPTZ,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    generation              BIGINT NOT NULL DEFAULT 0,
    probe_owner             VARCHAR(100),
    probe_job_id            BIGINT,
    probe_epoch             BIGINT,
    probe_reserved_until    TIMESTAMPTZ,
    probe_call_id           TEXT,
    probe_call_until        TIMESTAMPTZ,

    CONSTRAINT ck_circuit_contract
        CHECK (
            generation >= 0 AND consecutive_failures >= 0
            AND state IN ('CLOSED', 'OPEN', 'HALF_OPEN')
            AND (state <> 'OPEN' OR opened_until IS NOT NULL)
            AND (
                (state = 'HALF_OPEN' AND probe_owner IS NOT NULL AND probe_job_id IS NOT NULL
                    AND probe_epoch IS NOT NULL AND probe_epoch >= 0 AND probe_reserved_until IS NOT NULL)
                OR (state <> 'HALF_OPEN' AND probe_owner IS NULL AND probe_job_id IS NULL
                    AND probe_epoch IS NULL AND probe_reserved_until IS NULL
                    AND probe_call_id IS NULL AND probe_call_until IS NULL)
            )
            AND (
                (probe_call_id IS NULL AND probe_call_until IS NULL)
                OR (probe_call_id IS NOT NULL AND probe_call_until IS NOT NULL)
            )
        )
);

INSERT INTO external_circuit_breaker (name) VALUES ('embedding-api');


-- -----------------------------------------------------------------------------
-- external_circuit_result
--
-- 호출 결과를 call_id 단위로 남긴다. 어느 generation 에 대한 호출인지와
-- 실제로 상태에 반영됐는지(applied)를 함께 기록한다.
-- -----------------------------------------------------------------------------

CREATE TABLE external_circuit_result (
    breaker_name            VARCHAR(50) NOT NULL REFERENCES external_circuit_breaker(name),
    call_id                 TEXT NOT NULL,
    generation              BIGINT NOT NULL CHECK (generation >= 0),
    probe_owner             VARCHAR(100),
    outcome                 VARCHAR(20) NOT NULL
        CHECK (outcome IN ('SUCCESS', 'FAILURE', 'RATE_LIMIT', 'PERMANENT', 'CONFIGURATION')),
    applied                 BOOLEAN NOT NULL,
    resulting_state         VARCHAR(20) NOT NULL
        CHECK (resulting_state IN ('CLOSED', 'OPEN', 'HALF_OPEN')),
    created_at              TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    PRIMARY KEY (breaker_name, call_id)
);

CREATE INDEX idx_circuit_result_generation
    ON external_circuit_result (breaker_name, generation);
