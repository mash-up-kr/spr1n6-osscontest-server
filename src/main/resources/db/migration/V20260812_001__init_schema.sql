-- -----------------------------------------------------------------------------
-- 0. 확장
--
-- opencrypto 는 설치하지 않는다. 컬럼 타입(BYTEA)은 확장과 무관하고
-- 암복호화는 쿼리 시점에 일어나므로, 확장이 없는 local 에서도 스키마 생성은 성공한다.
-- -----------------------------------------------------------------------------

CREATE EXTENSION IF NOT EXISTS vector;


-- -----------------------------------------------------------------------------
-- 1. tenant
-- -----------------------------------------------------------------------------

CREATE TABLE tenant (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                        VARCHAR(100) NOT NULL,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- -----------------------------------------------------------------------------
-- 2. app_user
--
-- user 는 PostgreSQL 예약어이므로 app_user 를 사용한다.
-- email 은 UNIQUE 제약과 로그인 조회에 쓰이므로 암호화 대상에서 제외했다.
-- -----------------------------------------------------------------------------

CREATE TABLE app_user (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id                   BIGINT NOT NULL,
    email                       VARCHAR(255) NOT NULL,
    name                        BYTEA NOT NULL,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_app_user_tenant
        FOREIGN KEY (tenant_id)
        REFERENCES tenant(id),
    CONSTRAINT uk_app_user_tenant_email
        UNIQUE (tenant_id, email)
);

COMMENT ON COLUMN app_user.name IS '암호화 대상. opencrypto 함수로 암복호화한다.';


-- -----------------------------------------------------------------------------
-- 3. document
-- -----------------------------------------------------------------------------

CREATE TABLE document (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id                   BIGINT NOT NULL,
    owner_principal_id          VARCHAR(255) NOT NULL,

    title                       VARCHAR(255) NOT NULL,
    latest_upload_version_no    BIGINT NOT NULL DEFAULT 0,
    latest_embedding_version_no BIGINT NOT NULL DEFAULT 0,
    searchable_version_id       BIGINT,

    deleted_at                  TIMESTAMPTZ,
    purged_at                   TIMESTAMPTZ,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_document_tenant
        FOREIGN KEY (tenant_id)
        REFERENCES tenant(id),
    CONSTRAINT uk_document_id_tenant
        UNIQUE (id, tenant_id),
    CONSTRAINT ck_document_latest_upload_version_no
        CHECK (latest_upload_version_no >= 0),
    CONSTRAINT ck_document_latest_embedding_version_no
        CHECK (latest_embedding_version_no >= 0),
    CONSTRAINT ck_document_embedding_not_ahead_of_upload
        CHECK (latest_embedding_version_no <= latest_upload_version_no),
    CONSTRAINT ck_document_purged_after_deleted
        CHECK (purged_at IS NULL OR deleted_at IS NOT NULL)
);

COMMENT ON COLUMN document.latest_upload_version_no IS
    '마지막으로 발급된 version_no. 다음 버전 번호 채번에 쓰는 카운터.';
COMMENT ON COLUMN document.latest_embedding_version_no IS
    '임베딩이 완료된 가장 최신 version_no.';
COMMENT ON COLUMN document.searchable_version_id IS
    '검색 대상 document_version 의 PK. latest_embedding_version_no 이하 버전만 지정한다.';
COMMENT ON COLUMN document.purged_at IS
    '물리 정리 완료 시각. 청크 삭제와 원본 삭제가 모두 끝난 뒤 마지막에 기록한다. '
    'NULL 이면 아직 정리되지 않았다는 뜻이므로 스케줄러가 다시 집는다.';


-- -----------------------------------------------------------------------------
-- 4. document_version
-- -----------------------------------------------------------------------------

CREATE TABLE document_version (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id                 BIGINT NOT NULL,
    version_no                  BIGINT NOT NULL,

    source_object_key           VARCHAR(1024) NOT NULL,
    original_filename           BYTEA NOT NULL,
    mime_type                   VARCHAR(100) NOT NULL,
    file_size                   BIGINT NOT NULL,
    content_hash                VARCHAR(128) NOT NULL,

    source_metadata             JSONB,
    extracted_metadata          JSONB,

    chunk_count                 INTEGER,
    indexed_at                  TIMESTAMPTZ,

    created_by_principal_id     VARCHAR(255) NOT NULL,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_document_version_document
        FOREIGN KEY (document_id)
        REFERENCES document(id),
    CONSTRAINT uk_document_version
        UNIQUE (document_id, version_no),
    CONSTRAINT uk_document_version_id_document
        UNIQUE (id, document_id),
    CONSTRAINT ck_document_version_no
        CHECK (version_no > 0),
    CONSTRAINT ck_document_version_file_size
        CHECK (file_size >= 0),
    CONSTRAINT ck_document_version_chunk_count
        CHECK (chunk_count IS NULL OR chunk_count >= 0)
);

COMMENT ON COLUMN document_version.original_filename IS
    '암호화 대상. opencrypto 함수로 암복호화한다.';
COMMENT ON COLUMN document_version.extracted_metadata IS
    '문서 파싱이 아니라 AI 가 생성한 메타데이터.';


-- document.searchable_version_id 의 복합 FK 는 document_version 생성 후 추가한다.
ALTER TABLE document
ADD CONSTRAINT fk_document_searchable_version
    FOREIGN KEY (searchable_version_id, id)
    REFERENCES document_version(id, document_id);


-- -----------------------------------------------------------------------------
-- 5. outbox_event
--
-- DOCUMENT_DELETED 는 문서 단위 이벤트라 document_version_id 가 NULL 이다.
-- status 이하는 릴레이 서버의 폴링 발행용 컬럼이다.
-- -----------------------------------------------------------------------------

CREATE TABLE outbox_event (
    id                          UUID PRIMARY KEY,
    tenant_id                   BIGINT NOT NULL,
    document_id                 BIGINT NOT NULL,
    document_version_id         BIGINT,
    retry_of_event_id           UUID,

    event_type                  VARCHAR(50) NOT NULL,
    event_schema_version        INTEGER NOT NULL DEFAULT 1,
    payload                     JSONB NOT NULL,
    trace_id                    VARCHAR(255),

    status                      VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    publish_attempt_count       INTEGER NOT NULL DEFAULT 0,
    next_attempt_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    locked_by                   VARCHAR(255),
    locked_at                   TIMESTAMPTZ,
    published_at                TIMESTAMPTZ,
    last_error_message          TEXT,

    created_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_outbox_document_tenant
        FOREIGN KEY (document_id, tenant_id)
        REFERENCES document(id, tenant_id),
    CONSTRAINT fk_outbox_document_version
        FOREIGN KEY (document_version_id, document_id)
        REFERENCES document_version(id, document_id),
    CONSTRAINT ck_outbox_schema_version
        CHECK (event_schema_version > 0),
    CONSTRAINT ck_outbox_event_type
        CHECK (event_type IN (
            'INDEXING_REQUESTED',
            'DOCUMENT_DELETED'
        )),
    CONSTRAINT ck_outbox_indexing_request_target
        CHECK (event_type <> 'INDEXING_REQUESTED'
               OR document_version_id IS NOT NULL),
    CONSTRAINT ck_outbox_document_deleted_target
        CHECK (event_type <> 'DOCUMENT_DELETED'
               OR document_version_id IS NULL),
    CONSTRAINT ck_outbox_status
        CHECK (status IN (
            'PENDING',
            'PUBLISHING',
            'PUBLISHED',
            'DEAD'
        )),
    CONSTRAINT ck_outbox_publish_attempt_count
        CHECK (publish_attempt_count >= 0)
);

COMMENT ON COLUMN outbox_event.document_version_id IS
    'INDEXING_REQUESTED 는 버전 단위라 값을 가지고, DOCUMENT_DELETED 는 문서 단위라 NULL 이다.';
COMMENT ON COLUMN outbox_event.next_attempt_at IS
    '이 시각부터 발행 대상이 된다. 최초 행도 값을 가진다.';
COMMENT ON COLUMN outbox_event.retry_of_event_id IS
    '재발행 건이 가리키는 원본 이벤트. 신규 업로드 건은 NULL 이다.';
COMMENT ON COLUMN outbox_event.locked_by IS
    '이 행을 집은 릴레이 인스턴스. 릴레이를 다중화하면 한 행을 둘이 집는 것을 막는다.';
COMMENT ON COLUMN outbox_event.locked_at IS
    'PUBLISHING 으로 바뀐 시각. 발행 중 죽은 행을 회수하는 기준이라 릴레이가 한 대여도 필요하다.';
COMMENT ON COLUMN outbox_event.trace_id IS
    '트리거는 애플리케이션 트레이스 컨텍스트에 접근할 수 없으므로, '
    '트랜잭션에서 SET LOCAL app.trace_id 로 넘긴 값을 읽는다.';


-- -----------------------------------------------------------------------------
-- 6. indexing_job
-- -----------------------------------------------------------------------------

CREATE TABLE indexing_job (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_event_id             UUID NOT NULL,
    document_id                 BIGINT NOT NULL,
    document_version_id         BIGINT NOT NULL,

    status                      VARCHAR(30) NOT NULL,
    attempt_count               INTEGER NOT NULL DEFAULT 0,
    next_retry_at               TIMESTAMPTZ,

    worker_id                   VARCHAR(255),
    last_error_code             VARCHAR(100),
    last_error_message          TEXT,
    trace_id                    VARCHAR(255),

    started_at                  TIMESTAMPTZ,
    completed_at                TIMESTAMPTZ,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_indexing_job_source_event
        UNIQUE (source_event_id),
    CONSTRAINT fk_indexing_job_document_version
        FOREIGN KEY (document_version_id, document_id)
        REFERENCES document_version(id, document_id),
    CONSTRAINT ck_indexing_job_status
        CHECK (status IN (
            'PENDING',
            'PROCESSING',
            'RETRY_WAIT',
            'COMPLETED',
            'FAILED'
        )),
    CONSTRAINT ck_indexing_job_attempt_count
        CHECK (attempt_count >= 0)
);

-- source_event_id 에는 의도적으로 FK 를 걸지 않는다.
-- Outbox 행은 발행 후 정리할 수 있어야 하지만 Job 의 이력은 더 오래 남긴다.


-- -----------------------------------------------------------------------------
-- 7. document_chunk
--
-- VECTOR(1536) 의 차원은 잠정값이다. 임베딩 모델이 확정되면 변경한다.
-- tenant_id 는 document 에서 내려온 반정규화 컬럼이다. 검색 필터와 벡터 컬럼을
-- 같은 테이블에 두기 위한 것이라 값의 일치는 복합 FK 로 강제한다.
-- -----------------------------------------------------------------------------

CREATE TABLE document_chunk (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id                   BIGINT NOT NULL,
    document_version_id         BIGINT NOT NULL,
    document_id                 BIGINT NOT NULL,
    chunk_no                    INTEGER NOT NULL,

    content                     TEXT NOT NULL,
    content_hash                VARCHAR(128) NOT NULL,
    token_count                 INTEGER,

    page_from                   INTEGER,
    page_to                     INTEGER,
    section_path                VARCHAR(1024),
    metadata                    JSONB,

    embedding                   VECTOR(1536) NOT NULL,
    embedded_at                 TIMESTAMPTZ NOT NULL,

    created_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_document_chunk
        UNIQUE (document_version_id, chunk_no),
    CONSTRAINT fk_document_chunk_version_document
        FOREIGN KEY (document_version_id, document_id)
        REFERENCES document_version(id, document_id),
    CONSTRAINT fk_document_chunk_document_tenant
        FOREIGN KEY (document_id, tenant_id)
        REFERENCES document(id, tenant_id),
    CONSTRAINT ck_document_chunk_no
        CHECK (chunk_no >= 0),
    CONSTRAINT ck_document_chunk_token_count
        CHECK (token_count IS NULL OR token_count >= 0),
    CONSTRAINT ck_document_chunk_page_range
        CHECK (
            page_from IS NULL
            OR page_to IS NULL
            OR page_from <= page_to
        )
);


