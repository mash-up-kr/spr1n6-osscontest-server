CREATE TABLE document_access_scope (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id                   BIGINT NOT NULL,
    document_id                 BIGINT NOT NULL,

    principal_type              VARCHAR(30) NOT NULL,
    principal_id                VARCHAR(255) NOT NULL,
    permission                  VARCHAR(20) NOT NULL DEFAULT 'READ',

    granted_by_principal_id     VARCHAR(255) NOT NULL,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_access_scope_document_tenant
        FOREIGN KEY (document_id, tenant_id)
        REFERENCES document(id, tenant_id),
    CONSTRAINT uk_document_access_scope
        UNIQUE (document_id, principal_type, principal_id),
    CONSTRAINT ck_access_scope_principal_type
        CHECK (principal_type IN (
            'USER',
            'TENANT'
        )),
    CONSTRAINT ck_access_scope_permission
        CHECK (permission IN ('READ', 'WRITE', 'ADMIN'))
);


-- -----------------------------------------------------------------------------
-- 9. 인덱스
--
-- 벡터 인덱스(HNSW)는 벡터 검색 담당이 별도 마이그레이션 파일로 관리한다.
-- -----------------------------------------------------------------------------

CREATE INDEX idx_document_tenant_active
    ON document (tenant_id, id)
    WHERE deleted_at IS NULL;

-- 삭제 정리 스케줄러의 스캔 대상.
CREATE INDEX idx_document_pending_purge
    ON document (deleted_at)
    WHERE deleted_at IS NOT NULL AND purged_at IS NULL;

CREATE INDEX idx_document_version_document
    ON document_version (document_id, version_no DESC);

-- 릴레이 폴링 전용. 발행이 끝난 행은 빠지므로 Outbox 가 쌓여도 크기가 유지된다.
CREATE INDEX idx_outbox_pending
    ON outbox_event (next_attempt_at, id)
    WHERE status = 'PENDING';

-- PUBLISHING 상태로 멈춘 좀비 행 회수
CREATE INDEX idx_outbox_stuck
    ON outbox_event (locked_at)
    WHERE status = 'PUBLISHING';

-- 한 문서 버전에 진행 중인 Job 은 하나만 존재하도록 강제한다.
CREATE UNIQUE INDEX uq_indexing_job_active_version
    ON indexing_job (document_version_id)
    WHERE status IN ('PENDING', 'PROCESSING', 'RETRY_WAIT');

CREATE INDEX idx_indexing_job_retry
    ON indexing_job (status, next_retry_at)
    WHERE status IN ('PENDING', 'RETRY_WAIT');

-- 한 문서 버전의 인덱싱 이력 조회
CREATE INDEX idx_indexing_job_version
    ON indexing_job (document_version_id, created_at DESC);

CREATE INDEX idx_chunk_document_version
    ON document_chunk (document_version_id, chunk_no);

-- 하이브리드 검색의 키워드 쪽. 색인 구성(simple)은 검색 튜닝 결과에 따라
-- 별도 마이그레이션으로 바꿀 수 있다.
CREATE INDEX idx_document_chunk_content_tsv
    ON document_chunk USING GIN (to_tsvector('simple', content));

CREATE INDEX idx_access_scope_principal
    ON document_access_scope (
        tenant_id,
        principal_type,
        principal_id,
        document_id
    );


-- -----------------------------------------------------------------------------
-- 10. Outbox 트리거
-- -----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION fn_outbox_indexing_requested()
RETURNS TRIGGER AS $$
DECLARE
    v_tenant_id BIGINT;
    v_event_id  UUID;
BEGIN
    SELECT tenant_id
      INTO v_tenant_id
      FROM document
     WHERE id = NEW.document_id;

    v_event_id := gen_random_uuid();

    INSERT INTO outbox_event (
        id,
        tenant_id,
        document_id,
        document_version_id,
        event_type,
        event_schema_version,
        payload,
        trace_id
    )
    VALUES (
        v_event_id,
        v_tenant_id,
        NEW.document_id,
        NEW.id,
        'INDEXING_REQUESTED',
        1,
        jsonb_build_object(
            'tenantId',        v_tenant_id,
            'versionNo',       NEW.version_no,
            'sourceObjectKey', NEW.source_object_key,
            'mimeType',        NEW.mime_type,
            'fileSize',        NEW.file_size,
            'contentHash',     NEW.content_hash,
            'occurredAt',      to_char(
                                   CURRENT_TIMESTAMP AT TIME ZONE 'UTC',
                                   'YYYY-MM-DD"T"HH24:MI:SS"Z"'
                               )
        ),
        current_setting('app.trace_id', true)
    );

    -- 알림은 유실될 수 있으므로 릴레이는 폴링도 함께 수행해야 한다.
    -- pg_notify 는 8000바이트 제한이 있어 ID 만 보내고 릴레이가 다시 조회한다.
    PERFORM pg_notify('outbox_event', v_event_id::text);

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


CREATE TRIGGER trg_document_version_outbox
    AFTER INSERT ON document_version
    FOR EACH ROW
    EXECUTE FUNCTION fn_outbox_indexing_requested();


-- 삭제는 deleted_at 을 채우는 소프트 삭제이므로 UPDATE 를 감시한다.
-- 청크 정리는 워커가 이 이벤트를 받아서 수행한다.
CREATE OR REPLACE FUNCTION fn_outbox_document_deleted()
RETURNS TRIGGER AS $$
DECLARE
    v_event_id UUID;
BEGIN
    v_event_id := gen_random_uuid();

    INSERT INTO outbox_event (
        id,
        tenant_id,
        document_id,
        document_version_id,
        event_type,
        event_schema_version,
        payload,
        trace_id
    )
    VALUES (
        v_event_id,
        NEW.tenant_id,
        NEW.id,
        NULL,
        'DOCUMENT_DELETED',
        1,
        jsonb_build_object(
            'tenantId',   NEW.tenant_id,
            'deletedAt',  to_char(
                              NEW.deleted_at AT TIME ZONE 'UTC',
                              'YYYY-MM-DD"T"HH24:MI:SS"Z"'
                          ),
            'occurredAt', to_char(
                              CURRENT_TIMESTAMP AT TIME ZONE 'UTC',
                              'YYYY-MM-DD"T"HH24:MI:SS"Z"'
                          )
        ),
        current_setting('app.trace_id', true)
    );

    PERFORM pg_notify('outbox_event', v_event_id::text);

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


-- WHEN 절이 이벤트를 삭제 시점 한 번으로 제한한다.
-- deleted_at 이 이미 채워진 행을 다시 UPDATE 해도 이벤트가 늘지 않는다.
CREATE TRIGGER trg_document_deleted_outbox
    AFTER UPDATE ON document
    FOR EACH ROW
    WHEN (OLD.deleted_at IS NULL AND NEW.deleted_at IS NOT NULL)
    EXECUTE FUNCTION fn_outbox_document_deleted();
